def make_rootfs(root, *, user=True, server=True, second_server=False, pyautogui=True, flask=True, xlib=True, dbus=True,
                xvfb=True, xorg=False, dummy=False, gnome=True, os_release=True, unit=True, server_src=SERVER_SRC,
                python3=True, system_bus=True, login=True):
    def w(rel, text=b"", mode=None):
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "wb").write(text if isinstance(text, bytes) else text.encode())
        if mode:
            os.chmod(p, mode)
    if os_release:
        w("etc/os-release", 'ID=ubuntu\nVERSION_ID="22.04"\nPRETTY_NAME="Ubuntu 22.04.4 LTS"\nVERSION_CODENAME=jammy\n')
    w("etc/passwd", "root:x:0:0:root:/root:/bin/bash\n" + ("messagebus:x:103:106::/nonexistent:/usr/sbin/nologin\n" if system_bus else "")
      + ("user:x:1000:1000:User:/home/user:/bin/bash\n" if user else "")
      + "nobody:x:65534:65534::/nonexistent:/usr/sbin/nologin\n")
    for name, present in (("python3", python3), ("dbus-daemon", dbus), ("Xvfb", xvfb), ("Xorg", xorg), ("gnome-shell", gnome),
                          ("nautilus", True)):
        if present:
            w(f"usr/bin/{name}", "#!/bin/sh\n", 0o755)
    if dummy:
        w("usr/lib/xorg/modules/drivers/dummy_drv.so", "x")
    for mod, present in (("pyautogui", pyautogui), ("flask", flask), ("Xlib", xlib)):
        if present:
            w(f"usr/lib/python3/dist-packages/{mod}/__init__.py", "")
    if server:
        w("home/user/server/main.py", server_src)
        w("home/user/server/screen_recording.py", "")
        os.makedirs(os.path.join(root, "home/user/Desktop"), exist_ok=True)
    if second_server:
        w("opt/other/main.py", server_src)
    if unit and server:
        w("etc/systemd/system/osworld_server.service", UNIT)
    if gnome:
        w("usr/share/xsessions/ubuntu.desktop", "[Desktop Entry]\nName=Ubuntu\nExec=env GNOME_SHELL_SESSION_MODE=ubuntu "
          "/usr/bin/gnome-session --session=ubuntu\nType=Application\nDesktopNames=ubuntu:GNOME\n")
        w("usr/share/gdm/env.d/10-test.env", "# comment\nXDG_CONFIG_DIRS=/etc/xdg/xdg-ubuntu:/etc/xdg\nPATH=/evil\nXDG_X=$HOME/x\n")
    if gnome and login:
        # the image's autologin, as the real OSWorld image has it (gdm3 + gdm-autologin PAM + gnome-session), in miniature
        w("etc/pam.d/gdm-autologin", "auth optional pam_gnome_keyring.so\n@include common-session\n"
          "session required pam_env.so readenv=1\nsession required pam_env.so readenv=1 user_readenv=1 envfile=/etc/default/locale\n"
          "session optional pam_gnome_keyring.so auto_start\n")
        w("etc/pam.d/common-session", "session required pam_unix.so\n")
        w("etc/environment", 'PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/usr/games:/snap/bin"\n')
        w("etc/default/locale", '#  File generated by update-locale\nLANG="en_HK.UTF-8"\nLANGUAGE="en_HK:en"\n')
        w("etc/security/pam_env.conf", "# comments only\n")
        w("etc/gdm3/Xsession", "#!/bin/sh\nexport FROM_XSESSION=1\neval exec \"$@\"\n", 0o755)
        w("usr/lib/systemd/user-environment-generators/30-env-d", "#!/bin/sh\necho PATH=$PATH:/snap/bin\n", 0o755)
        w("usr/lib/systemd/user-environment-generators/90not-executable", "#!/bin/sh\necho NO=1\n", 0o644)
        w("etc/systemd/user-environment-generators/60-masked", "", 0o755)          # an empty file masks /usr/lib's of that name
        w("usr/lib/systemd/user-environment-generators/60-masked", "#!/bin/sh\necho MASKED=1\n", 0o755)
        w("usr/lib/systemd/system-environment-generators/snapd-env-generator", "#!/bin/sh\necho PATH=$PATH:/snap/bin\n", 0o755)
        w("usr/share/gnome-session/sessions/ubuntu.session", "[GNOME Session]\nName=Ubuntu\nRequiredComponents=org.gnome.Shell;"
          "org.gnome.SettingsDaemon.XSettings;org.gnome.SettingsDaemon.MediaKeys;\n")
