class Res:
    def __init__(self, rc=0, out="", err=""):
        self.rc, self.out, self.err = rc, out, err

    def result(self):
        return ExecResult(self.rc, self.out, self.err, 0.0, 0.01, "t")


class ScriptExec:
    """Executor driven by a function(argv)->Res|None (None = rc 0, empty). Records every argv."""
    is_fake = True

    def __init__(self, fn=None):
        self.fn = fn or (lambda argv: None)
        self.calls = []

    def run(self, cmd, timeout):
        argv = list(cmd.argv)
        self.calls.append(argv)
        r = self.fn(argv)
        return (r or Res()).result()

    def names(self):
        return [c[0] for c in self.calls]


class World:
    """Fake process world for the arm: slot trees, proxies, images, pidfiles."""

    def __init__(self, **flags):
        self.f = {"unkillable": set(), "server_dead": False, "dump_fails": False, "restore_fails": False, "no_init": False,
                  **flags}
        self.trees = {}
        self.proxies = {}
        self.next = 5000
        self.events = []
        self.dir_marker = {}
        self.last_launch = None
        self.scoped_units = []
        self.pid_unit = {}          # fake init pid -> the systemd scope it runs in (None = whatever cgroup the caller was in)
        self.pending_unit = None

    def spawn(self, kind, marker):
        self.next += 1
        (self.trees if kind == "tree" else self.proxies)[self.next] = marker
        return self.next


class FakeHost:
    def __init__(self, world, kind, tools=("criu", "unshare", "nsenter", "setsid", "systemd-run")):
        self.w, self.kind, self.tools = world, kind, set(tools)

    @property
    def table(self):
        return self.w.trees if self.kind == "tree" else self.w.proxies

    def which(self, t):
        return f"/usr/bin/{t}" if t in self.tools else None

    def find_init(self, marker):
        hits = [p for p, m in self.w.trees.items() if m == marker]
        return None if self.w.f["no_init"] else (hits[0] if hits else None)

    def find_all_inits(self, marker):
        return [p for p, m in self.table.items() if m == marker] if self.kind == "tree" else []

    def find_marker_procs(self, marker):
        return [p for p, m in self.table.items() if m == marker]

    def read_pid(self, path):
        try:
            return int(open(path).read())
        except (OSError, ValueError):
            return None

    def terminate(self, pid, marker, grace_s=10.0, require_init=True):
        if pid in self.w.f["unkillable"]:
            return False, "still alive after SIGKILL"
        self.table.pop(pid, None)
        self.w.events.append(("terminate", self.kind, pid))
        return True, "terminated"


def arm_exec(world, state_dir_of=None):
    """ScriptExec emulating the system commands the arm issues."""
    def fn(argv):
        name = argv[0]
        if name in ("criu", "unshare", "systemd-run") and argv[1:] == ["--version"]:
            return Res(0, f"{name} 1.0\n")
        if name == "systemd-run" and "criu" in argv:
            world.events.append(("scoped_restore", argv[argv.index("--unit") + 1], list(argv)))
            world.scoped_units.append(argv[argv.index("--unit") + 1])
            world.pending_unit = argv[argv.index("--unit") + 1]
            try:
                return fn(argv[argv.index("--") + 1:])
            finally:
                world.pending_unit = None
        if name == "systemd-run":
            marker = argv[argv.index("--marker") + 1]
            world.dir_marker[os.path.dirname(argv[argv.index("--plan") + 1])] = marker
            world.pid_unit[world.spawn("tree", marker)] = argv[argv.index("--unit") + 1]
            world.events.append(("launch", marker))
            if world.f.get("service_log"):               # what the real tree leaves in the upper layer
                name, _, text = world.f["service_log"].partition(": ")
                plan = json.load(open(argv[argv.index("--plan") + 1]))
                os.makedirs(os.path.join(plan["upper"], "var/log/sharedos"), exist_ok=True)
                open(os.path.join(plan["upper"], "var/log/sharedos", name), "w").write(text)
            world.last_launch = argv
            return None
        if name == "setsid" and "sharedos_rootfs.proxy" in argv:
            world.spawn("proxy", argv[argv.index("--marker") + 1])
            world.events.append(("proxy", int(argv[argv.index("--init-pid") + 1])))
            return None
        if name == "criu" and argv[1] == "dump":
            if world.f["dump_fails"]:
                return Res(1, "", "Error: dump failed")
            if world.f.get("dump_fails_quiet"):           # real criu: stderr empty, the diagnosis is only in the -o log
                open(argv[argv.index("-o") + 1], "w").write("(00.10) Dumping\n(00.20) Error (criu/cr-dump.c:1): fake dump error\n")
                return Res(1, "", "")
            images = argv[argv.index("-D") + 1]
            open(os.path.join(images, "core-1.img"), "w").write("x")
            for p in [p for p, m in list(world.trees.items())]:
                world.trees.pop(p)   # dump without --leave-running stops the tree
            world.events.append(("dump", "--leave-running" in argv))
            return None
        if name == "criu" and argv[1] == "restore":
            if world.f["restore_fails"]:
                return Res(1, "", "Error: restore failed")
            if world.f.get("restore_fails_quiet"):
                open(argv[argv.index("-o") + 1], "w").write("(00.30) Error (criu/fsnotify.c:1486): fake: Too many open files\n")
                return Res(1, "", "")
            images = argv[argv.index("-D") + 1]
            pidfile = argv[argv.index("--pidfile") + 1]
            pid = world.spawn("tree", world.dir_marker[os.path.dirname(images)])
            world.pid_unit[pid] = world.pending_unit
            open(pidfile, "w").write(str(pid))
            world.events.append(("restore", pid))
            return None
        if name == "cp":
            src, dst = argv[-2], argv[-1]
            shutil.copytree(src, dst, symlinks=True)
            world.events.append(("cp", src, dst))
            return None
        if name == "findmnt":
            return Res(1)
        if name in ("criu", "unshare", "systemd-run") and argv[1:] == ["--version"]:
            return Res(0, f"{name} 1.0\n")
        return None
    return ScriptExec(fn)


def fake_cgroup_reader(world, vcpus=4, memory_mib=4096):
    """cgroup readback driven by the fake world: a pid started through systemd-run reads back its scope and the
    preregistered limits unless a world flag says otherwise; a pid started any other way reads back a foreign cgroup."""
    def read(pid):
        if world.f.get("cgroup_unreadable"):
            raise OSError("cgroup.procs: no such file")
        unit = world.pid_unit.get(pid)
        path = f"/system.slice/{unit}" if unit else "/user.slice/user-0.slice/session-1.scope"
        lim = {"cpu_max": f"{vcpus * 100000} 100000", "memory_max": str(memory_mib * 1048576), "swap_max": "0"}
        lim.update(world.f.get("cgroup_limits") or {})
        stray = {str(p): "/system.slice/other.scope" for p in world.f.get("stray_descendants", ())}
        return {"path": path, **lim, "procs": [pid], "descendants": list(world.f.get("stray_descendants", ())),
                "descendant_cgroups": stray, "init_start_ticks": f"{pid}00"}
    return read


class FakeUserns:
    """Recording stand-in for harden.HostUserns (host-root idmapped mount, chown/chmod): the lower layer it returns is the image path
    itself, so the arm's plans and restore roots read as before while every call is recorded."""

    def __init__(self):
        self.calls = []

    def idmapped_lower(self, lower, base):
        self.calls.append(("idmapped_lower", lower, base))
        return lower

    def shift_owner(self, root, base):
        self.calls.append(("shift_owner", root, base))
        return []

    def prepare_access(self, state_root, slot_dir, plan_file, owned_dirs, base):
        self.calls.append(("prepare_access", state_root, slot_dir, plan_file, tuple(owned_dirs), base))
