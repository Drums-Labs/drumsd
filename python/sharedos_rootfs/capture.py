"""Capture: checkpoint a RUNNING slot (provisioned, restored or branched) into a NEW origin slot that children branch from, and let the
parent continue from that same checkpoint.  Harness-side, on top of pageshare.py; the pinned sources are untouched.

    SHAREDOS_ROOTFS_CONFIG=config.json python -m sharedos_rootfs.capture capture --slot P --into Q [--no-continue] [--mode-parent pool]

The pinned `candidate snapshot` can only checkpoint a slot that has never been checkpointed (no upper.snap, empty images).  A reached
state inside an episode lives in a slot that was restored from some earlier checkpoint, so it needs this verb:
  1. The same pre-dump gates as `candidate snapshot` (init pid and start time are the recorded ones, mount contract, loopback, network
     state, mount table, lock census and criu(8)'s lock enclosure condition), all recorded in Q.
  2. The reference process set for the alive gate (pid-namespace pid and comm of every user-space process, zombies excluded).
  3. `criu dump` of P's tree into Q/images (the pinned dump command line; the tree stops), the network-image manifest and the dumped
     lock record, then P's upper layer copied to Q/upper.snap while the tree is stopped (disk and memory are one consistent state).
  4. Q gets an ownership marker naming P, the records the restore gates compare against, and a slot.json whose `branched_from.tree_marker`
     is the marker that is really in the dumped argv (P's own argv marker, which for a branched P is its origin's).
  4b. With --leave-running: the dump leaves P's tree running and P's upper layer is copied by CRIU's own post-dump action
     (criu(8) --action-script, action "post-dump"), which CRIU runs after every image is written and BEFORE it unfreezes
     the tree (cr-dump.c cr_dump_finish: run_scripts(ACT_POST_DUMP) precedes delete_link_remaps() and pstree_switch_state()),
     so disk and memory are still one state and the link-remap names are still in the copy. P is not restored: it simply
     continues (its proxy is never stopped). The script's own timings are recorded in Q/post-dump.json.
  5. Unless --no-continue: P is re-based on Q (its images become hard links of Q's, its upper.snap a copy of Q's, the records Q's) and
     restored with every arm gate, so P continues as child 1.  P's previous images and records are moved aside, not deleted.
"""

