//! CRIU action script (`--action-script`), the Rust replacement for `python3 -I locks.py --hook DIR`.
//!
//! CRIU runs the script at EVERY action (pre-restore, setup-namespaces, post-setup-namespaces, post-restore,
//! network-unlock, pre-resume, post-resume) and waits for it each time. A Python start costs 70-165 ms per action on
//! the drums-linux host (measured from a restore log), so the hook alone was ~0.77 s of a 1.69 s restore. This hook
//! returns at once for actions it ignores and does the pre-resume work in a few milliseconds:
//!
//! * `locks-pre-resume.json`: the lock census of the restored tree while every task is still stopped
//!   (same fields the Python gate reads: `shape`, `tuples`, `tree_pids`, `by_pid_ns`, `by_children`, `locks`, `error`);
//! * `procs-pre-resume.json`: {namespace pid: comm} of every restored process, the alive gate's reference set.
//!
//! The script file itself is a two-line `sh` wrapper written per restore (CRIU executes the path with no arguments).

use crate::procfs::{self, RealProc};
use drumsd_core::locks;
use serde_json::json;
use std::fs;
use std::io;
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt};
use std::path::{Path, PathBuf};

/// Write `<dir>/hook.sh` that runs `<exe> hook <dir>`.
pub fn write_script(dir: &Path, exe: &Path) -> io::Result<PathBuf> {
    fs::DirBuilder::new().mode(0o700).create(dir)?;
    let p = dir.join("hook.sh");
    let mut f = fs::OpenOptions::new().write(true).create_new(true).mode(0o700).open(&p)?;
    use std::io::Write;
    writeln!(f, "#!/bin/sh\n# generated by drumsd: read-only census at CRIU's pre-resume action")?;
    writeln!(f, "exec '{}' hook '{}'", exe.display().to_string().replace('\'', ""), dir.display().to_string().replace('\'', ""))?;
    Ok(p)
}

/// One line per invocation in `<dir>/hook-times.jsonl`: action, start and end (epoch seconds), so the restore
/// log's gaps can be split into hook time and CRIU's own time.
fn note(dir: &str, action: &str, start: f64) {
    use std::io::Write;
    if let Ok(mut f) = fs::OpenOptions::new().create(true).append(true).open(Path::new(dir).join("hook-times.jsonl")) {
        let _ = writeln!(f, "{}", json!({"action": action, "start": start, "end": crate::now_epoch(), "pid": std::process::id()}));
    }
}

pub fn hook_main(dir: &str) -> i32 {
    let start = crate::now_epoch();
    let action = std::env::var("CRTOOLS_SCRIPT_ACTION").unwrap_or_default();
    if action == "setup-namespaces" && Path::new(dir).join("netns-lo-up").exists() {
        let rc = match lo_up(&std::env::var("CRTOOLS_INIT_PID").unwrap_or_default()) {
            Ok(()) => 0,
            Err(e) => {
                eprintln!("drumsd hook: lo up: {e}");
                let _ = fs::write(Path::new(dir).join("netns-lo-up.error"), e.to_string());
                1
            }
        };
        note(dir, &action, start);
        return rc;
    }
    if action != "pre-resume" {
        note(dir, &action, start);
        return 0;
    }
    // restore boost: put the slot's CPU limit back before any restored task runs (all are still stopped here)
    let boost = Path::new(dir).join("cpu-restore.json");
    if let Ok(b) = fs::read(&boost) {
        let v: serde_json::Value = serde_json::from_slice(&b).unwrap_or_default();
        let want = v["cpu_max"].as_str().unwrap_or("");
        let mut errs = vec![];
        for p in v["paths"].as_array().cloned().unwrap_or_default() {
            if let Some(p) = p.as_str() {
                if let Err(e) = fs::write(Path::new(p).join("cpu.max"), want) {
                    errs.push(format!("{p}: {e}"));
                }
            }
        }
        let _ = fs::write(Path::new(dir).join("cpu-restore.done"), serde_json::to_vec(&json!({"at": crate::now_epoch(), "errors": errs})).unwrap_or_default());
    }
    let rc = pre_resume(dir);
    if Path::new(dir).join("softdirty-clear").exists() {
        clear_soft_dirty(dir);
    }
    note(dir, &action, start);
    rc
}

/// Clear the soft-dirty bits of every restored process while all of them are still stopped (pre-resume), so a later
/// `criu dump --track-mem --prev-images-dir <the images restored from>` writes only the pages written since this
/// restore. Result in `<dir>/softdirty-clear.done`: the pids cleared and any error; drumsd uses the restore as an
/// incremental base only when the file says every process was cleared.
fn clear_soft_dirty(dir: &str) {
    let t0 = crate::now_epoch();
    // the base's time for CRIU's pid-reuse check (--prev-images-uptime): read before the first clear, so every task
    // restored here started before it and any task started after the restore is dumped in full
    let uptime_us: Option<u64> = fs::read_to_string("/proc/uptime").ok().and_then(|u| u.split_whitespace().next().and_then(|x| x.parse::<f64>().ok())).map(|s| (s * 1e6) as u64);
    let root = std::env::var("CRTOOLS_INIT_PID").unwrap_or_default();
    let mut errs: Vec<String> = vec![];
    let mut done: Vec<i64> = vec![];
    match root.parse::<i64>() {
        Ok(pid) => {
            let p = RealProc;
            let (by_ns, _) = procfs::ns_members_and_procs(pid as i32);
            let mut tree: Vec<i64> = by_ns.iter().chain(locks::children_walk(&p, pid).iter()).copied().chain(std::iter::once(pid)).collect();
            tree.sort();
            tree.dedup();
            for t in tree {
                match fs::write(format!("/proc/{t}/clear_refs"), "4") {
                    Ok(()) => done.push(t),
                    Err(e) => errs.push(format!("{t}: {e}")),
                }
            }
        }
        Err(e) => errs.push(format!("CRTOOLS_INIT_PID {root:?}: {e}")),
    }
    let rec = json!({"pids": done, "errors": errs, "ok": errs.is_empty() && !done.is_empty() && uptime_us.is_some(), "uptime_us": uptime_us,
                     "seconds": crate::now_epoch() - t0});
    let _ = fs::write(Path::new(dir).join("softdirty-clear.done"), serde_json::to_vec(&rec).unwrap_or_default());
}

/// Bring `lo` up inside the restored init's (empty) network namespace: the kernel then adds 127.0.0.1/8 and ::1
/// itself. Used only with `--empty-ns net`; the netns gate still compares links, addresses and routes to the dump.
fn lo_up(init: &str) -> Result<(), String> {
    let pid: i32 = init.parse().map_err(|e| format!("CRTOOLS_INIT_PID {init:?}: {e}"))?;
    let ns = fs::File::open(format!("/proc/{pid}/ns/net")).map_err(|e| e.to_string())?;
    use std::os::fd::AsRawFd;
    if unsafe { libc::setns(ns.as_raw_fd(), libc::CLONE_NEWNET) } != 0 {
        return Err(format!("setns: {}", io::Error::last_os_error()));
    }
    let sk = unsafe { libc::socket(libc::AF_INET, libc::SOCK_DGRAM | libc::SOCK_CLOEXEC, 0) };
    if sk < 0 {
        return Err(format!("socket: {}", io::Error::last_os_error()));
    }
    let mut ifr: libc::ifreq = unsafe { std::mem::zeroed() };
    for (i, b) in b"lo".iter().enumerate() {
        ifr.ifr_name[i] = *b as libc::c_char;
    }
    let r = unsafe { libc::ioctl(sk, libc::SIOCGIFFLAGS, &mut ifr) };
    if r < 0 {
        return Err(format!("SIOCGIFFLAGS: {}", io::Error::last_os_error()));
    }
    unsafe { ifr.ifr_ifru.ifru_flags |= (libc::IFF_UP | libc::IFF_RUNNING) as libc::c_short };
    let r = unsafe { libc::ioctl(sk, libc::SIOCSIFFLAGS, &ifr) };
    unsafe { libc::close(sk) };
    if r < 0 {
        return Err(format!("SIOCSIFFLAGS: {}", io::Error::last_os_error()));
    }
    Ok(())
}

fn pre_resume(dir: &str) -> i32 {
    let action = "pre-resume";
    let root = std::env::var("CRTOOLS_INIT_PID").unwrap_or_default();
    let mut rec = json!({"action": action, "census_start": crate::now_epoch(), "epoch": crate::now_epoch(), "init_pid": root, "writer": "drumsd"});
    let res: Result<(), String> = (|| {
        let pid: i64 = root.parse().map_err(|e| format!("CRTOOLS_INIT_PID {root:?}: {e}"))?;
        let p = RealProc;
        // one pass over /proc gives both the pid-namespace members and the alive gate's reference set
        let (by_ns, procs) = procfs::ns_members_and_procs(pid as i32);
        let by_children = locks::children_walk(&p, pid);
        let mut tree: Vec<i64> = by_ns.iter().chain(by_children.iter()).copied().chain(std::iter::once(pid)).collect();
        tree.sort();
        tree.dedup();
        let census = locks::census_parallel(&p, &tree, 4)?;
        let shape: Vec<_> = locks::shape_of_census(&census).into_iter().map(|(a, b, c, d)| json!([a, b, c, d])).collect();
        rec["tree_pids"] = json!(tree);
        rec["by_pid_ns"] = json!(by_ns);
        rec["by_children"] = json!(by_children);
        rec["locks"] = json!(census);
        rec["tuples"] = json!(locks::census_tuples(&census));
        rec["shape"] = json!(shape);
        fs::write(Path::new(dir).join("procs-pre-resume.json"), serde_json::to_vec(&json!({"init_pid": pid, "procs": procs})).map_err(|e| e.to_string())?)
            .map_err(|e| e.to_string())?;
        Ok(())
    })();
    if let Err(e) = res {
        rec["error"] = json!(e);
    }
    let path = Path::new(dir).join("locks-pre-resume.json");
    match fs::OpenOptions::new().write(true).create_new(true).open(&path) {
        Ok(mut f) => {
            use std::io::Write;
            let _ = f.write_all(&serde_json::to_vec_pretty(&rec).unwrap_or_default());
        }
        Err(e) => eprintln!("drumsd hook: {}: {e}", path.display()),
    }
    0
}
