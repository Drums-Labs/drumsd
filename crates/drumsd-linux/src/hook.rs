//! CRIU action script (`--action-script`), the Rust replacement for `python3 -I locks.py --hook DIR`.
//!
//! CRIU runs the script at EVERY action (pre-restore, setup-namespaces, post-setup-namespaces, post-restore,
//! network-unlock, pre-resume, post-resume) and waits for it each time. A Python start costs 70-165 ms per action on
//! the drums-linux host (measured from a restore log), so the hook alone was ~0.77 s of a 1.69 s restore. This hook
//! returns at once for actions it ignores and does the pre-resume work in a few milliseconds:
//!
//! * `locks-pre-resume.json`: the lock census of the restored tree while every task is still stopped
//!   (same fields the Python gate reads: `shape`, `tuples`, `tree_pids`, `by_pid_ns`, `by_children`, `locks`, `error`);
//! * `procs-pre-resume.json`: {namespace pid: comm} of every restored process, the alive gate's reference set.
//!
//! The script file itself is a two-line `sh` wrapper written per restore (CRIU executes the path with no arguments).

use crate::procfs::{self, RealProc};
use drumsd_core::locks;
use serde_json::json;
use std::fs;
use std::io;
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt};
use std::path::{Path, PathBuf};

/// Write `<dir>/hook.sh` that runs `<exe> hook <dir>`.
pub fn write_script(dir: &Path, exe: &Path) -> io::Result<PathBuf> {
    fs::DirBuilder::new().mode(0o700).create(dir)?;
    let p = dir.join("hook.sh");
    let mut f = fs::OpenOptions::new().write(true).create_new(true).mode(0o700).open(&p)?;
    use std::io::Write;
    writeln!(f, "#!/bin/sh\n# generated by drumsd: read-only census at CRIU's pre-resume action")?;
    writeln!(f, "exec '{}' hook '{}'", exe.display().to_string().replace('\'', ""), dir.display().to_string().replace('\'', ""))?;
    Ok(p)
}

pub fn hook_main(dir: &str) -> i32 {
    let action = std::env::var("CRTOOLS_SCRIPT_ACTION").unwrap_or_default();
    if action != "pre-resume" {
        return 0;
    }
    let root = std::env::var("CRTOOLS_INIT_PID").unwrap_or_default();
    let mut rec = json!({"action": action, "epoch": crate::now_epoch(), "init_pid": root, "writer": "drumsd"});
    let res: Result<(), String> = (|| {
        let pid: i64 = root.parse().map_err(|e| format!("CRTOOLS_INIT_PID {root:?}: {e}"))?;
        let p = RealProc;
        let by_ns = locks::pid_ns_members(&p, pid);
        let by_children = locks::children_walk(&p, pid);
        let mut tree: Vec<i64> = by_ns.iter().chain(by_children.iter()).copied().chain(std::iter::once(pid)).collect();
        tree.sort();
        tree.dedup();
        let census = locks::census(&p, &tree)?;
        let shape: Vec<_> = locks::shape_of_census(&census).into_iter().map(|(a, b, c, d)| json!([a, b, c, d])).collect();
        rec["tree_pids"] = json!(tree);
        rec["by_pid_ns"] = json!(by_ns);
        rec["by_children"] = json!(by_children);
        rec["locks"] = json!(census);
        rec["tuples"] = json!(locks::census_tuples(&census));
        rec["shape"] = json!(shape);
        let procs = procfs::ns_procs(pid as i32);
        fs::write(Path::new(dir).join("procs-pre-resume.json"), serde_json::to_vec(&json!({"init_pid": pid, "procs": procs})).map_err(|e| e.to_string())?)
            .map_err(|e| e.to_string())?;
        Ok(())
    })();
    if let Err(e) = res {
        rec["error"] = json!(e);
    }
    let path = Path::new(dir).join("locks-pre-resume.json");
    match fs::OpenOptions::new().write(true).create_new(true).open(&path) {
        Ok(mut f) => {
            use std::io::Write;
            let _ = f.write_all(&serde_json::to_vec_pretty(&rec).unwrap_or_default());
        }
        Err(e) => eprintln!("drumsd hook: {}: {e}", path.display()),
    }
    0
}
